    public static HadithItem getTodayHadith() {
        if (manualIndex >= 0 && manualIndex < HADITHS.size()) {
            return HADITHS.get(manualIndex);
        }
        int day = Calendar.getInstance().get(Calendar.DAY_OF_YEAR);
        int index = day % HADITHS.size();
        return HADITHS.get(index);
    }

    public static HadithItem nextHadith() {
        if (manualIndex < 0) {
            manualIndex = Calendar.getInstance().get(Calendar.DAY_OF_YEAR) % HADITHS.size();
        }
        manualIndex = (manualIndex + 1) % HADITHS.size();
        return HADITHS.get(manualIndex);
    }
